# -*- coding: utf-8 -*-
"""`python -m build new-project`: a new project from its four inputs.

    python -m build new-project --code AMS11 --name "Amsterdam 11" --id <GUID>

writes
    AMS11/project.json                          the project GUID, name and (optional) client
    .github/workflows/refresh-AMS11.yml         its own twice-a-day refresh

The token is the repository secret VL_TOKEN_<CODE> (VL_TOKEN_AMS11); create it in GitHub, then
commit and push the two files. Each new workflow runs a few minutes after the previous
project's, so their pushes to gh-pages rarely meet (and are retried when they do).
"""
from __future__ import annotations

import glob
import json
import os
import re

from . import ROOT
from .build import KEY_RE
from .fetch import secret_name

GUID_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")
WORKFLOWS = os.path.join(ROOT, ".github", "workflows")

# 04:21 and 10:21 UTC = 09:51 and 15:51 IST; project n starts 4 minutes after project n-1
RUNS_UTC = ((4, 21), (10, 21))
STAGGER_MIN = 4

WORKFLOW = """name: "Refresh __CODE__ - __NAME__"

# Generated by `python -m build new-project`. Refreshes the __CODE__ page from VisiLean
# (3 API calls: task history, commitments, constraint log) and publishes it to the gh-pages
# branch, then asks the portfolio workflow to rebuild the landing page.
# Token: repository secret __SECRET__.

on:
  schedule:
__CRONS__
  workflow_dispatch:
    inputs:
      source:
        description: "Data source"
        type: choice
        default: live
        options: [live, sample]

permissions:
  contents: write   # push to gh-pages
  actions: write    # start the portfolio workflow

concurrency:
  group: refresh-__CODE__
  cancel-in-progress: false

jobs:
  refresh:
    runs-on: ubuntu-latest
    timeout-minutes: 20
    steps:
      - uses: actions/checkout@v4

      - uses: actions/setup-python@v5
        with:
          python-version: "3.12"

      # last good copy of the feeds: an outage gives a "stale" page instead of an empty one
      - name: Restore last good data
        uses: actions/cache@v4
        with:
          path: .cache
          key: vl-feed-__CODE__-${{ github.run_id }}
          restore-keys: |
            vl-feed-__CODE__-

      - name: Self-test calculation logic
        run: python -m build selftest

      - name: Fetch the published site
        run: bash .github/scripts/pages.sh fetch

      - name: Build __CODE__
        id: build
        env:
          __SECRET__: ${{ secrets.__SECRET__ }}
        run: |
          set -uo pipefail
          python -m build build --project "__CODE__" --source "${{ github.event.inputs.source || 'live' }}" --no-landing | tee build.log
          code=${PIPESTATUS[0]}
          echo "code=$code" >> "$GITHUB_OUTPUT"
          [ "$code" = "0" ] || [ "$code" = "2" ] || exit "$code"

      - name: Validate
        run: python -m build validate --project "__CODE__"

      - name: Scan for credentials
        run: bash .github/scripts/pages.sh scan "__CODE__"

      - name: Publish __CODE__
        run: bash .github/scripts/pages.sh publish "Refresh __CODE__" "__CODE__"

      - name: Refresh the portfolio page
        env:
          GH_TOKEN: ${{ github.token }}
        run: gh workflow run portfolio.yml --ref "${{ github.ref_name }}"

      # after publishing, so the page still shows the last good data
      - name: Report problems
        run: |
          state=$(python -c "import json; print(json.load(open('dist/__CODE__/build.json'))['state'])")
          echo "### __CODE__: $state" >> "$GITHUB_STEP_SUMMARY"
          if [ "${{ steps.build.outputs.code }}" = "2" ]; then
            echo "::error title=VisiLean token rejected::Fix repository secret __SECRET__"; exit 1
          fi
          if [ "$state" = "unavailable" ]; then
            echo "::error title=No data::__CODE__ has no data: check secret __SECRET__ and the project GUID"; exit 1
          fi
"""


def _crons(index: int) -> str:
    lines = []
    for h, m in RUNS_UTC:
        total = h * 60 + m + STAGGER_MIN * index
        hh, mm = divmod(total, 60)
        ist_h, ist_m = divmod(total + 330, 60)
        lines.append('    - cron: "%d %d * * *"   # %02d:%02d IST' % (mm, hh % 24, ist_h % 24, ist_m))
    return "\n".join(lines)


def workflow_text(code: str, name: str, index: int) -> str:
    safe_name = name.replace('"', "'")
    return (WORKFLOW.replace("__CRONS__", _crons(index)).replace("__SECRET__", secret_name(code))
            .replace("__CODE__", code).replace("__NAME__", safe_name))


def new_project(code: str, name: str, guid: str, client: str | None = None, force: bool = False) -> int:
    code, name, guid = code.strip(), name.strip(), guid.strip()
    if not KEY_RE.match(code):
        print("project code %r: use letters, digits, '.', '_' or '-', starting with a letter" % code)
        return 1
    if not GUID_RE.match(guid):
        print("project id %r is not a GUID (xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx)" % guid)
        return 1
    if not name:
        print("project name is empty")
        return 1
    pdir = os.path.join(ROOT, code)
    pj = os.path.join(pdir, "project.json")
    wf = os.path.join(WORKFLOWS, "refresh-%s.yml" % code)
    clash = [p for p in (pj, wf) if os.path.exists(p)]
    if clash and not force:
        print("already exists: %s (use --force to overwrite)" % ", ".join(os.path.relpath(p, ROOT) for p in clash))
        return 1
    for other in glob.glob(os.path.join(ROOT, "*", "project.json")):
        with open(other, encoding="utf-8") as f:
            o = json.load(f)
        if str(o.get("projectId", "")).lower() == guid.lower() and os.path.dirname(other) != pdir:
            print("project id already used by %s" % os.path.basename(os.path.dirname(other)))
            return 1

    # stagger: the next free slot after the refresh workflows that already exist
    index = len([p for p in glob.glob(os.path.join(WORKFLOWS, "refresh-*.yml")) if os.path.abspath(p) != os.path.abspath(wf)])

    cfg = {"key": code, "title": name}
    if client:
        cfg["client"] = client
    cfg.update({"projectId": guid, "facts": []})
    os.makedirs(pdir, exist_ok=True)
    with open(pj, "w", encoding="utf-8", newline="\n") as f:
        json.dump(cfg, f, indent=2, ensure_ascii=False)
        f.write("\n")
    os.makedirs(WORKFLOWS, exist_ok=True)
    with open(wf, "w", encoding="utf-8", newline="\n") as f:
        f.write(workflow_text(code, name, index))

    print("created %s" % os.path.relpath(pj, ROOT))
    print("created %s" % os.path.relpath(wf, ROOT))
    print("\nNext:")
    print("  1. GitHub -> Settings -> Secrets and variables -> Actions -> New repository secret:")
    print("     name %s, value = the VisiLean access token for this project" % secret_name(code))
    print("  2. Optional: add Contractor / Region / Country / City to %s/project.json -> facts" % code)
    print("  3. Commit and push both files. The page appears at <site>/%s/ after the first refresh" % code)
    print("     (Actions -> \"Refresh %s - %s\" -> Run workflow, or wait for the schedule)." % (code, name))
    return 0
